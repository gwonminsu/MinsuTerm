const get = (url) => new Promise((resolve, reject) => {
  https.get(url, { headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)' } }, (r) => {
    if (r.statusCode !== 200) { r.resume(); return reject(new Error(`${r.statusCode} ${url}`)); }
    const chunks = []; r.on('data', (c) => chunks.push(c)); r.on('end', () => resolve(Buffer.concat(chunks)));
  }).on('error', reject);
});

(async () => {
  const lines = ['// Generated by scripts/make-samples.js — real recordings for typing sounds (all CC0). Do not edit.', 'window.SAMPLES = {'];
  const credits = ['# Typing-sound samples', '', 'Every clip below is **CC0 (public domain)** on freesound.org — free to use and redistribute, no attribution required. Listed anyway, with thanks.', ''];
  let total = 0;
  for (const [theme, clips] of Object.entries(SAMPLES)) {
    lines.push(`  ${theme}: {`);
    credits.push(`## ${theme}`);
    for (const [name, [id, p]] of Object.entries(clips)) {
      const mp3 = await get(`https://cdn.freesound.org/previews/${p}-hq.mp3`);
      if (mp3.length < 1000 || mp3.slice(0, 3).toString() === '<!D') throw new Error(`bad file for ${theme}.${name}`);
      total += mp3.length;
      lines.push(`    ${name}: '${mp3.toString('base64')}',`);
      credits.push(`- ${name}: https://freesound.org/s/${id}/`);
      process.stdout.write(`${theme}.${name} ${(mp3.length / 1024).toFixed(0)}KB  `);
      await new Promise((r) => setTimeout(r, 150));
    }
    lines.push('  },');
    credits.push('');
  }
  lines.push('};', '');
  fs.writeFileSync(path.join(ROOT, 'src', 'renderer', 'samples.js'), lines.join('\n'));
  fs.writeFileSync(path.join(ROOT, 'SOUND-CREDITS.md'), credits.join('\n'));
  console.log(`\n→ src/renderer/samples.js (${(total / 1024).toFixed(0)} KB of MP3)`);
})().catch((e) => { console.error(e); process.exit(1); });
