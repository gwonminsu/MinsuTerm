'use strict';
/**
 * scripts/i18n/{en,ja,zh}.json (Korean phrase → translation) → src/i18n/*.json (main process)
 * and src/renderer/i18n-data.js (renderer). Checks every phrase is translated and keeps its "#" slots.
 *   node scripts/i18n-extract.js && node scripts/i18n-build.js
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const phrases = require('./i18n-phrases.json');
const LANGS = ['en', 'ja', 'zh'];
const out = {};
let problems = 0;
fs.mkdirSync(path.join(ROOT, 'src', 'i18n'), { recursive: true });
for (const l of LANGS) {
  const file = path.join(__dirname, 'i18n', `${l}.json`);
  if (!fs.existsSync(file)) { console.warn(`${l}: missing ${file}`); continue; }
  const d = JSON.parse(fs.readFileSync(file, 'utf8'));
  const clean = {};
  let missing = 0, slots = 0;
  for (const k of new Set([...phrases, ...Object.keys(d)])) {
    const v = d[k];
    if (typeof v !== 'string' || !v.length) { missing++; continue; }
    if ((k.match(/#/g) || []).length !== (v.match(/#/g) || []).length) { slots++; continue; }
    clean[k] = v;
  }
  problems += missing + slots;
  console.log(`${l}: ${phrases.filter((k) => k in clean).length}/${phrases.length} ok · missing ${missing} · wrong # ${slots}`);
  fs.writeFileSync(path.join(ROOT, 'src', 'i18n', `${l}.json`), JSON.stringify(clean, null, 1));
  out[l] = clean;
}
fs.writeFileSync(path.join(ROOT, 'src', 'renderer', 'i18n-data.js'),
  `// Generated by scripts/i18n-build.js from scripts/i18n/*.json — do not edit.\nwindow.I18N_DATA = ${JSON.stringify(out)};\n`);
console.log(problems ? `${problems} phrase(s) skipped (shown in Korean)` : 'all phrases translated');
